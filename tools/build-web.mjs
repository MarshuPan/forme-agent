// Reproducible, offline-at-runtime static Web assets with exact license inventory.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, readdir, mkdir, rm } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const frontend = join(root, 'frontend');
const output = join(root, 'crates/gateway/assets/product');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Unsupported build option');
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const normalized = (bytes) => bytes.toString('utf8').replaceAll('\r\n', '\n');

async function filesIn(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error('Symbolic links are not release inputs');
    if (entry.isDirectory()) found.push(...await filesIn(path));
    else if (entry.isFile()) found.push(path);
  }
  return found.sort();
}

const sourceFiles = [
  ...(await filesIn(join(frontend, 'src'))), ...(await filesIn(join(frontend, 'public'))),
  ...['index.html', 'package.json', 'package-lock.json', 'tsconfig.json', 'vite.config.ts'].map((path) => join(frontend, path)),
  fileURLToPath(import.meta.url),
].sort();
const sources = [];
for (const path of sourceFiles) sources.push({ path: relative(root, path).split(sep).join('/'), sha256: sha(normalized(await readFile(path))) });
const lock = JSON.parse(await readFile(join(frontend, 'package-lock.json'), 'utf8'));
const allowedLicenses = new Set(['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', '0BSD', 'CC0-1.0', '(MIT OR Apache-2.0)', '(MIT AND BSD-3-Clause)', '(MIT OR CC0-1.0)']);
const dependencies = [];
const notices = ['forme Web workbench — dependency license texts', 'Source code authored for forme; no DeepSeek source files imported.'];
for (const [path, value] of Object.entries(lock.packages)) {
  if (!path) continue;
  const reviewedBuildOnly = value.dev === true && value.license === 'MPL-2.0';
  if ((!allowedLicenses.has(value.license) && !reviewedBuildOnly) || !value.integrity?.startsWith('sha512-') || !value.resolved?.startsWith('https://registry.npmjs.org/')) throw new Error(`Unreviewed dependency source/license: ${path}`);
  const name = path.replace(/^node_modules\//, '');
  dependencies.push({ name, version: value.version, license: value.license, integrity: value.integrity, source: value.resolved, build_only: Boolean(value.dev), optional: Boolean(value.optional) });
  if (!value.dev) {
    const directory = join(frontend, path);
    const license = (await readdir(directory)).find((name) => /^license(?:\.md|\.txt)?$/i.test(name));
    if (!license) throw new Error(`Missing runtime license text: ${path}`);
    notices.push(`${name} ${value.version}\n${await readFile(join(directory, license), 'utf8')}`);
  }
}
// Fixed program and arguments; no shell or environment-derived build command.
execFileSync(process.execPath, [join(frontend, 'node_modules/typescript/bin/tsc'), '--noEmit'], { cwd: frontend, stdio: 'inherit' });
execFileSync(process.execPath, [join(frontend, 'node_modules/vite/bin/vite.js'), 'build'], { cwd: frontend, stdio: 'inherit' });
const assets = new Map();
for (const path of await filesIn(join(frontend, 'dist'))) {
  const name = relative(join(frontend, 'dist'), path).split(sep).join('/');
  if (!/^(index\.html|favicon\.svg|assets\/[A-Za-z0-9_-]+\.(js|css))$/.test(name)) throw new Error(`Unexpected release asset: ${name}`);
  assets.set(name, await readFile(path));
}
assets.set('LICENSES.txt', Buffer.from(notices.join('\n\n--------------------\n\n')));
assets.set('dependencies.json', Buffer.from(JSON.stringify({ schema_version: 1, dependencies }, null, 2) + '\n'));
const inventory = [...assets].map(([path, bytes]) => ({ path, sha256: sha(bytes), bytes: bytes.length })).sort((a, b) => a.path.localeCompare(b.path, 'en'));
const manifest = Buffer.from(JSON.stringify({ schema_version: 1, source_digest: sha(JSON.stringify(sources)), sources, files: inventory }, null, 2) + '\n');
assets.set('manifest.json', manifest);
const mime = (name) => name.endsWith('.js') ? 'text/javascript; charset=utf-8' : name.endsWith('.css') ? 'text/css; charset=utf-8' : name.endsWith('.html') ? 'text/html; charset=utf-8' : name.endsWith('.svg') ? 'image/svg+xml' : name.endsWith('.json') ? 'application/json' : 'text/plain; charset=utf-8';
const embedded = Buffer.from([
  '// Generated by tools/build-web.mjs. Do not hand-edit; source and digest are verified.',
  '#[rustfmt::skip]',
  'pub(super) fn asset(path: &str) -> Option<(&\'static str, &\'static [u8])> {',
  '    match path {',
  ...[...assets.keys()].sort().map((name) => `        ${JSON.stringify('/' + name)} => Some((${JSON.stringify(mime(name))}, include_bytes!("dist/${name}"))),`),
  '        _ => None,', '    }', '}', '',
].join('\n'));
if (check) {
  const existing = await filesIn(join(output, 'dist'));
  if (existing.length !== assets.size) throw new Error('Embedded asset set is stale');
  for (const [name, bytes] of assets) if (!(await readFile(join(output, 'dist', name))).equals(bytes)) throw new Error(`Embedded asset differs from source build: ${name}`);
  if (!(await readFile(join(output, 'embedded.rs'))).equals(embedded)) throw new Error('Embedded route table is stale');
} else {
  // Only this generator's explicit output directory is replaced. It never
  // traverses outside gateway/assets/product/dist or touches owner runtime data.
  const target = join(output, 'dist');
  if (target !== resolve(root, 'crates/gateway/assets/product/dist')) throw new Error('Invalid build target');
  await rm(target, { recursive: true, force: true });
  for (const [name, bytes] of assets) { const path = join(target, name); await mkdir(dirname(path), { recursive: true }); await writeFile(path, bytes); }
  await writeFile(join(output, 'embedded.rs'), embedded);
}
console.log(`Web static assets: ${check ? 'verified' : 'built'} (${assets.size} files; ${dependencies.length} locked dependencies)`);
